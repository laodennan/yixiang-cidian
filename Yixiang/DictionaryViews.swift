                        Button {
                            favorites.toggle(entry.word)
                        } label: {
                            Image(systemName: favorites.isFavorite(entry.word) ? "star.fill" : "star")
                                .font(.title2)
                        }
                        .buttonStyle(.borderless)
                    }
                }

                Text(entry.category)
                    .font(.subheadline)
                    .foregroundStyle(.secondary)

                if isGenerated {
                    Text("由 AI 现场生成，仅供参考；古诗句请以原文核对")
