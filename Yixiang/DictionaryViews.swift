// MARK: - 搜索页（含 AI 兜底：离线词库没有的词可调用用户配置的接口生成）

struct SearchView: View {
    @EnvironmentObject private var history: HistoryStore
    @EnvironmentObject private var customLexicon: CustomLexiconStore
    @ObservedObject private var dictStore = DictionaryStore.shared
    @ObservedObject private var webCache = WebSearchCache.shared

    @AppStorage("webSearchEnabled") private var webSearchEnabled = false
    @State private var query = ""
    @State private var showingSettings = false
    @State private var expandedCategories: Set<String> = []
    @State private var webSummary: WebSummary?
    @State private var webSummaryIsCached = false
    @State private var webLoading = false
    @State private var webError = ""
    @State private var autoGeneratedEntry: LexiconEntry?
    @State private var autoGenerating = false
    @State private var autoAIError = ""

    private var results: [LexiconEntry] {
        let base = Lexicon.search(query)
        let q = trimmedQuery
        guard !q.isEmpty else { return base }
        let mine = customLexicon.words.filter { $0.word.contains(q) && !base.contains($0) }
        return base + mine
    }

    /// 字典库联查结果（离线）：词典 Tab 没有的词，先看字典里有没有；
    /// 防抖 + 后台搜索，不在主线程每敲一字扫全库
    @State private var dictMatches = DictResults()

    private var webFallbackURL: URL {
        let encoded = trimmedQuery.addingPercentEncoding(withAllowedCharacters: .urlQueryAllowed) ?? trimmedQuery
        return URL(string: "https://www.baidu.com/s?wd=\(encoded)") ?? URL(string: "https://www.baidu.com")!
    }

    private var trimmedQuery: String {
        query.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    var body: some View {
        NavigationStack {
            List {
                if trimmedQuery.isEmpty {
                    if !customLexicon.words.isEmpty {
                        NavigationLink(destination: MyWordsView()) {
                            HStack {
                                Text("我的词条")
                                Spacer()
                                Text("\(customLexicon.words.count) 个")
                                    .foregroundStyle(.secondary)
                            }
                        }
                    }
                    if !customLexicon.sentences.isEmpty {
                        NavigationLink(destination: MySentencesView()) {
                            HStack {
                                Text("我的词句")
                                Spacer()
                                Text("\(customLexicon.sentences.count) 条")
                                    .foregroundStyle(.secondary)
                            }
                        }
                    }
                    // 分类折叠：首页只显示 12 个分类，默认收起，点开展开看词
                    ForEach(Lexicon.categories, id: \.self) { category in
                        DisclosureGroup(
                            isExpanded: Binding(
                                get: { expandedCategories.contains(category) },
                                set: { expanded in
                                    if expanded {
                                        expandedCategories.insert(category)
                                    } else {
                                        expandedCategories.remove(category)
                                    }
                                }
                            )
                        ) {
                            ForEach(Lexicon.entries(in: category)) { entry in
                                NavigationLink(destination: EntryDetailView(entry: entry)) {
                                    HStack {
                                        Text(entry.word)
                                        if customLexicon.isWordAdded(entry.word) {
                                            Text("我的")
                                                .font(.caption)
                                                .foregroundStyle(.secondary)
                                        }
                                    }
                                }
                            }
                        } label: {
                            HStack {
                                Text(category)
                                Spacer()
                                Text("\(Lexicon.entries(in: category).count) 个")
                                    .foregroundStyle(.secondary)
                            }
                        }
                    }
                    // 场景灵感库入口：放在 12 分类折叠下方
                    NavigationLink(destination: SceneListView()) {
                        HStack {
                            Text("场景灵感库")
                            Spacer()
                            Text("\(SceneLibrary.entries.count) 个场景")
                                .foregroundStyle(.secondary)
                        }
                    }
                } else {
                    // 搜索命中场景词时，在结果区上方加一个“场景灵感”小节
                    if let scene = SceneLibrary.entry(for: trimmedQuery) {
                        VStack(alignment: .leading, spacing: 4) {
                            Text("场景灵感")
                                .font(.subheadline)
                                .foregroundStyle(.secondary)
                            NavigationLink(destination: SceneDetailView(scene: scene)) {
                                Text("“\(scene.keyword)”的灵感：人物表现、环境描写、动作细节与参考句子")
                            }
                        }
                    }
                    ForEach(results) { entry in
                        NavigationLink(destination: EntryDetailView(entry: entry)) {
                            HStack {
                                Text(entry.word)
                                if customLexicon.isWordAdded(entry.word) {
                                    Text("我的")
                                        .font(.caption)
                                        .foregroundStyle(.secondary)
                                }
                            }
                        }
                    }
                }
            }
            .safeAreaPadding(.bottom, 96)
            .navigationTitle("意象词典")
            .searchable(text: $query, prompt: "输入意象，如月亮")
            .overlay {
                if results.isEmpty && !trimmedQuery.isEmpty {
                    ScrollView {
                        VStack(alignment: .leading, spacing: 24) {
                            Text("意象词库里还没有「\(trimmedQuery)」")
                                .font(.headline)

                            // 字典库联查（离线）：词典没有的词，字典里可能有
                            if dictStore.loaded {
                                if !dictMatches.isEmpty {
                                    VStack(alignment: .leading, spacing: 12) {
                                        Text("字典里找到了")
                                            .font(.headline)
                                        if !dictMatches.idioms.isEmpty {
                                            Text("成语")
                                                .font(.subheadline)
                                                .foregroundStyle(.secondary)
                                            ForEach(Array(dictMatches.idioms.prefix(5)), id: \.word) { item in
                                                NavigationLink(destination: DictIdiomDetailView(item: item)) {
                                                    VStack(alignment: .leading, spacing: 2) {
                                                        Text(item.word)
                                                        Text(item.explanation)
                                                            .font(.callout)
                                                            .foregroundStyle(.secondary)
                                                            .lineLimit(1)
                                                    }
                                                }
                                            }
                                        }
                                        if !dictMatches.words.isEmpty {
                                            Text("词语")
                                                .font(.subheadline)
                                                .foregroundStyle(.secondary)
                                            ForEach(Array(dictMatches.words.prefix(5)), id: \.word) { item in
                                                NavigationLink(destination: DictWordDetailView(item: item)) {
                                                    VStack(alignment: .leading, spacing: 2) {
                                                        Text(item.word)
                                                        Text(item.explanation)
                                                            .font(.callout)
                                                            .foregroundStyle(.secondary)
                                                            .lineLimit(1)
                                                    }
                                                }
                                            }
                                        }
                                        if !dictMatches.chars.isEmpty {
                                            Text("汉字")
                                                .font(.subheadline)
                                                .foregroundStyle(.secondary)
                                            ForEach(Array(dictMatches.chars.prefix(3)), id: \.word) { item in
                                                NavigationLink(destination: DictCharDetailView(item: item)) {
                                                    VStack(alignment: .leading, spacing: 2) {
                                                        Text(item.word)
                                                        Text(item.explanation)
                                                            .font(.callout)
                                                            .foregroundStyle(.secondary)
                                                            .lineLimit(1)
                                                    }
                                                }
                                            }
                                        }
                                        if !dictMatches.xiehouyu.isEmpty {
                                            Text("歇后语")
                                                .font(.subheadline)
                                                .foregroundStyle(.secondary)
                                            ForEach(Array(dictMatches.xiehouyu.prefix(3)), id: \.riddle) { item in
                                                NavigationLink(destination: DictXiehouyuDetailView(item: item)) {
                                                    VStack(alignment: .leading, spacing: 2) {
                                                        Text(item.riddle)
                                                        Text(item.answer)
                                                            .font(.callout)
                                                            .foregroundStyle(.secondary)
                                                            .lineLimit(1)
                                                    }
                                                }
                                            }
                                        }
                                    }
                                }
                            } else {
                                HStack(spacing: 8) {
                                    ProgressView()
                                    Text("正在加载离线字典…")
                                        .font(.callout)
                                        .foregroundStyle(.secondary)
                                }
                            }

                            // 维基百科（免费接口，无需 Key；结果自动缓存到本机）
                            // 输入停稳后自动显示，旁边小备注说明来源；
                            // 只对纯中文词触发，拼音半成品不自动查；
                            // 开关在设置页，默认关闭，关闭时整块不显示也不联网
                            if isPureCJKQuery && webSearchEnabled {
                                VStack(alignment: .leading, spacing: 12) {
                                Text("维基百科")
                                    .font(.headline)
                                Text("以下为维基百科的公开词条摘要，仅供参考")
                                    .font(.caption)
                                    .foregroundStyle(.secondary)
                                if let summary = webSummary {
                                    VStack(alignment: .leading, spacing: 8) {
                                        Text(summary.title)
                                            .font(.headline)
                                        Text(summary.extract)
                                        HStack {
                                            if webSummaryIsCached {
                                                Text("本地缓存 · \(MySentencesView.dateFormatter.string(from: summary.fetchedAt))")
                                                    .font(.caption)
                                                    .foregroundStyle(.secondary)
                                            }
                                            Spacer()
                                            AddToLexiconButton(text: summary.extract, source: "联网搜索")
                                            CopyButton(text: summary.extract)
                                        }
                                        if let url = URL(string: summary.pageURL) {
                                            Link("来源：维基百科", destination: url)
                                                .font(.callout)
                                        }
                                        Button("重新获取") {
                                            Task { await fetchWeb(for: trimmedQuery, forceRefresh: true) }
                                        }
                                        .font(.callout)
                                    }
                                    .padding()
                                    .background(Color.secondary.opacity(0.1))
                                    .cornerRadius(12)
                                } else if webLoading {
                                    ProgressView("正在维基百科搜索…")
                                } else if !webError.isEmpty {
                                    Text(webError)
                                        .foregroundStyle(.red)
                                        .font(.callout)
                                    Link("用浏览器搜索「\(trimmedQuery)」", destination: webFallbackURL)
                                        .font(.callout)
                                } else {
                                    ProgressView("正在搜索…")
                                }
                            }
                            }

                            // AI 生成：输入停稳后自动显示在当前页，旁边小备注说明来源
                            // AI 不受维基开关影响，只受纯中文门禁约束
                            if isPureCJKQuery {
                                VStack(alignment: .leading, spacing: 12) {
                                Text("AI 生成")
                                    .font(.headline)
                                Text("由 AI 现场生成，仅供参考；古诗句请以原文核对")
                                    .font(.caption)
                                    .foregroundStyle(.secondary)
                                if let entry = autoGeneratedEntry {
                                    VStack(alignment: .leading, spacing: 12) {
                                        Text(entry.word)
                                            .font(.headline)
                                        Text(entry.category)
                                            .font(.subheadline)
                                            .foregroundStyle(.secondary)
                                        VStack(alignment: .leading, spacing: 8) {
                                            Text("古诗句")
                                                .font(.subheadline)
                                                .foregroundStyle(.secondary)
                                            ForEach(entry.poems) { poem in
                                                HStack(alignment: .top) {
                                                    VStack(alignment: .leading, spacing: 2) {
                                                        Text(poem.text)
                                                        if !poem.attribution.isEmpty {
                                                            Text(poem.attribution)
                                                                .font(.caption)
                                                                .foregroundStyle(.secondary)
                                                        }
                                                    }
                                                    Spacer()
                                                    SentenceStarButton(text: poem.text, source: "AI 生成")
                                                    MaterialBookmarkButton(text: poem.text, source: "AI 生成")
                                                    CopyButton(text: poem.text)
                                                }
                                            }
                                        }
                                        VStack(alignment: .leading, spacing: 8) {
                                            Text("生动表达")
                                                .font(.subheadline)
                                                .foregroundStyle(.secondary)
                                            ForEach(entry.expressions, id: \.self) { line in
                                                HStack(alignment: .top) {
                                                    Text(line)
                                                    Spacer()
                                                    SentenceStarButton(text: line, source: "AI 生成")
                                                    MaterialBookmarkButton(text: line, source: "AI 生成")
                                                    CopyButton(text: line)
                                                }
                                            }
                                        }
                                        Button(customLexicon.isWordAdded(entry.word) ? "已加入我的词典" : "加入我的词典") {
                                            customLexicon.addWord(entry)
                                        }
                                        .buttonStyle(.bordered)
                                        .disabled(customLexicon.isWordAdded(entry.word))
                                    }
                                    .padding()
                                    .background(Color.secondary.opacity(0.1))
                                    .cornerRadius(12)
                                } else if autoGenerating {
                                    ProgressView("AI 正在生成…")
                                } else if !autoAIError.isEmpty {
                                    Text(autoAIError)
                                        .foregroundStyle(.red)
                                        .font(.callout)
                                    Button("重新生成") {
                                        Task { await autoGenerate(for: trimmedQuery) }
                                    }
                                    .buttonStyle(.bordered)
                                } else if !AISettings.hasKey {
                                    Text("AI 生成需要配置 API Key")
                                        .font(.callout)
                                        .foregroundStyle(.secondary)
                                    Button("去设置 API Key") {
                                        showingSettings = true
                                    }
                                    .font(.callout)
                                } else {
                                    ProgressView("正在准备…")
                                }
                                }
                            }
                        }
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .padding()
                    }
                }
            }
            .onAppear {
                dictStore.load()
            }
            .onChange(of: trimmedQuery) { _, _ in
                webSummary = nil
                webSummaryIsCached = false
                webError = ""
                autoGeneratedEntry = nil
                autoAIError = ""
                dictMatches = DictResults()
            }
            .task(id: "\(trimmedQuery)#\(dictStore.loaded)") {
                // 词典联查：停稳 300ms 后放后台跑，旧任务随输入变化自动取消
                let word = trimmedQuery
                guard !word.isEmpty, dictStore.loaded else { return }
                try? await Task.sleep(nanoseconds: 300_000_000)
                let start = Date()
                let found = await Task.detached(priority: .userInitiated) {
                    DictionaryStore.shared.search(word, scope: .all)
                }.value
                guard word == trimmedQuery else { return }
                dictMatches = found
                let ms = Int(Date().timeIntervalSince(start) * 1000)
                let tag = ms > 300 ? "慢搜索" : "联查"
                AppLog.log(tag: tag, "词典联查「\(word)」耗时 \(ms)ms，成语 \(found.idioms.count)/词语 \(found.words.count)/汉字 \(found.chars.count)/歇后语 \(found.xiehouyu.count)")
            }
            .task(id: trimmedQuery) {
                // 输入停稳后自动查一次（维基百科与 AI 生成并行），
                // 避免每敲一个字就调一次接口；输入变化时旧任务自动取消
                let word = trimmedQuery
                guard !word.isEmpty else { return }
                try? await Task.sleep(nanoseconds: 800_000_000)
                await autoSearch(word: word)
            }
            .onChange(of: showingSettings) { _, isShowing in
                // 从设置页回来时（如刚填好 Key），对当前词补一次自动搜索
                if !isShowing, !trimmedQuery.isEmpty, results.isEmpty {
                    Task { await autoSearch(word: trimmedQuery) }
                }
            }
            .onChange(of: webSearchEnabled) { _, enabled in
                // 维基开关从关变开、且当前正处在词典空结果页时，为当前词补查一次
                if enabled, !trimmedQuery.isEmpty, results.isEmpty {
                    Task { await autoSearch(word: trimmedQuery) }
                }
            }
            .toolbar {
                ToolbarItem(placement: .topBarTrailing) {
                    Button {
                        showingSettings = true
                    } label: {
                        Image(systemName: "gearshape")
                    }
                }
            }
            .sheet(isPresented: $showingSettings) {
                SettingsView()
            }
        }
    }

    /// 是否纯中文词：含汉字且不含 ASCII 字母。拼音半成品（如 hao、灏ha）
    /// 不自动联网/AI，避免无用请求刷屏（1.7 日志教训）。
    static func isPureCJK(_ word: String) -> Bool {
        guard PinyinKey.containsCJK(word) else { return false }
        return !word.unicodeScalars.contains { scalar in
            (scalar.value >= 65 && scalar.value <= 90) || (scalar.value >= 97 && scalar.value <= 122)
        }
    }

    private var isPureCJKQuery: Bool {
        Self.isPureCJK(trimmedQuery)
    }

    /// 取消不算失败：用户继续打字导致旧任务取消时，不显示红字、不记失败日志
    private func isCancellation(_ error: Error) -> Bool {
        if error is CancellationError { return true }
        if let urlError = error as? URLError { return urlError.code == .cancelled }
        if case let AIError.underlying(inner) = error { return isCancellation(inner) }
        return false
    }

    /// 自动搜索：词库里已有结果时不需要（空结果页根本不显示）；
    /// 否则维基百科与 AI 生成并行跑一次，结果直接显示在当前页。
    /// 维基百科那一路只在设置开关打开时跑，AI 那一路不受开关影响。
    private func autoSearch(word: String) async {
        guard Self.isPureCJK(word) else { return }
        let base = Lexicon.search(word)
        let mine = customLexicon.words.filter { $0.word.contains(word) && !base.contains($0) }
        guard base.isEmpty && mine.isEmpty else { return }
        if webSearchEnabled {
            async let web: Void = fetchWeb(for: word)
            async let ai: Void = autoGenerate(for: word)
            _ = await web
            _ = await ai
        } else {
            await autoGenerate(for: word)
        }
    }

    /// AI 自动生成：无 Key 时不调用接口，只显示去设置提示
    private func autoGenerate(for word: String) async {
        guard !word.isEmpty, AISettings.hasKey else { return }
        guard autoGeneratedEntry?.word != word else { return }
        autoAIError = ""
        autoGenerating = true
        defer { autoGenerating = false }
        let start = Date()
        do {
            let entry = try await AIClient.generateEntry(for: word)
            history.addGenerated(word: entry.word, poems: entry.poems, expressions: entry.expressions)
            autoGeneratedEntry = entry
            let ms = Int(Date().timeIntervalSince(start) * 1000)
            AppLog.log(tag: "AI生成", "「\(word)」生成成功，耗时 \(ms)ms")
        } catch {
            // 取消不算失败：用户继续打字导致旧任务取消时不显示红字、不记日志
            if isCancellation(error) { return }
            autoAIError = (error as? AIError)?.errorDescription ?? "生成失败，请重试"
            AppLog.log(tag: "AI生成失败", "「\(word)」\(autoAIError)")
        }
    }

    /// 联网搜索：先查本机缓存（有缓存直接显示、不断网也能看），没有才联网；
    /// 联网到的结果自动缓存到本机，并记入历史。
    private func fetchWeb(for word: String, forceRefresh: Bool = false) async {
        guard !word.isEmpty else { return }
        if !forceRefresh, let cached = webCache.cached(word) {
            webSummary = cached
            webSummaryIsCached = true
            webError = ""
            return
        }
        webError = ""
        webLoading = true
        defer { webLoading = false }
        let start = Date()
        do {
            let summary = try await WebSearchService.fetchSummary(for: word)
            webCache.save(summary)
            webSummary = summary
            webSummaryIsCached = false
            history.addWebSearch(word: word, summary: summary.extract)
            let ms = Int(Date().timeIntervalSince(start) * 1000)
            AppLog.log(tag: "联网", "维基百科「\(word)」联网获取成功，耗时 \(ms)ms")
        } catch WebSearchError.notFound {
            webSummary = nil
            webError = "维基百科上没有「\(word)」的词条"
            AppLog.log(tag: "联网", "维基百科「\(word)」无词条")
        } catch {
            // 取消不算失败：用户继续打字导致旧任务取消时不显示红字、不记日志
            if isCancellation(error) { return }
            webSummary = nil
            webError = "联网搜索失败，请检查网络后重试"
            AppLog.log(tag: "联网失败", "维基百科「\(word)」\(error.localizedDescription)")
        }
    }
}

// MARK: - 联网搜索：中文维基百科免费接口，无需 Key；结果缓存在本机

struct WebSummary: Codable, Hashable {
    let word: String
    let title: String
    let extract: String
    let pageURL: String
    let fetchedAt: Date
}

enum WebSearchError: Error {
    case notFound
    case network
}

enum WebSearchService {
    private struct WikiSummary: Decodable {
        let title: String?
        let extract: String?
        let content_urls: ContentURLs?

        struct ContentURLs: Decodable {
            let desktop: PageURL?

            struct PageURL: Decodable {
                let page: String?
            }
        }
    }

    static func fetchSummary(for word: String) async throws -> WebSummary {
        let encoded = word.addingPercentEncoding(withAllowedCharacters: .urlPathAllowed) ?? word
        guard let url = URL(string: "https://zh.wikipedia.org/api/rest_v1/page/summary/\(encoded)") else {
            throw WebSearchError.network
        }
        var request = URLRequest(url: url)
        request.setValue("Wenqi/1.6 (iOS personal dictionary app)", forHTTPHeaderField: "User-Agent")
        let (data, response) = try await URLSession.shared.data(for: request)
        guard let http = response as? HTTPURLResponse else {
            throw WebSearchError.network
        }
        guard http.statusCode == 200 else {
            throw WebSearchError.notFound
        }
        let decoded = try JSONDecoder().decode(WikiSummary.self, from: data)
        guard let extract = decoded.extract, !extract.isEmpty else {
            throw WebSearchError.notFound
        }
        let pageURL = decoded.content_urls?.desktop?.page ?? "https://zh.wikipedia.org/wiki/\(encoded)"
        return WebSummary(word: word, title: decoded.title ?? word, extract: extract, pageURL: pageURL, fetchedAt: Date())
    }
}

/// 联网搜索结果的本机缓存：按词存，重复搜直接显示，断网也能看
final class WebSearchCache: ObservableObject {
    static let shared = WebSearchCache()

    private let key = "webSearchCache"

    @Published private(set) var items: [String: WebSummary] = [:]

    private init() {
        if let data = UserDefaults.standard.data(forKey: key),
           let decoded = try? JSONDecoder().decode([String: WebSummary].self, from: data) {
            items = decoded
        }
    }

    func cached(_ word: String) -> WebSummary? {
        items[word]
    }

    func save(_ summary: WebSummary) {
        items[summary.word] = summary
        UserDefaults.standard.set(try? JSONEncoder().encode(items), forKey: key)
    }

    func clear() {
        items = [:]
        UserDefaults.standard.removeObject(forKey: key)
    }
}

