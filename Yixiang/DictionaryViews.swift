                            CopyButton(text: line)
                        }
                        Divider()
                    }
                }
            }
            .padding()
        }
        .safeAreaPadding(.bottom, 96)
        .navigationTitle(entry.word)
        .navigationBarTitleDisplayMode(.inline)
    }
}

